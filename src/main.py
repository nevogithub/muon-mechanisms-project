import argparse
import torch

from .utils import set_seed, load_config
from .dataset.build_dataset import build_dataset, build_dataloader
from .model.build_model import build_model
from .optim.build_optimizer import build_optimizer
from .optim.build_scheduler import build_scheduler
from .trainer.build_trainer import build_trainer


def get_parser():
    parser = argparse.ArgumentParser(
        description="MLOpt Benchmark",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    # ==========================================================
    # Config
    # ==========================================================
    parser.add_argument(
        "--config",
        type=str,
        required=True,
        help="Path to a single-experiment YAML/JSON config generated by the suite runner",
    )

    # ==========================================================
    # Reproducibility
    # ==========================================================
    parser.add_argument(
        "--seed",
        type=int,
        help="Random seed",
    )

    # ==========================================================
    # Device
    # ==========================================================
    parser.add_argument(
        "--device",
        type=str,
        default="cuda",
        choices=["cpu", "cuda", "mps"],
        help="Device to use for training",
    )

    # ==========================================================
    # Dataset
    # ==========================================================
    parser.add_argument("--dataset", type=str, help="Dataset name")
    parser.add_argument("--data-root", type=str, help="Dataset root path")
    parser.add_argument("--batch-size", type=int, help="Batch size")
    parser.add_argument("--num-workers", type=int, help="Number of data loader workers")

    # ==========================================================
    # Model
    # ==========================================================
    parser.add_argument("--model", type=str, help="Model name")
    parser.add_argument("--num-classes", type=int, help="Number of output classes")

    # ==========================================================
    # Training
    # ==========================================================
    parser.add_argument("--epochs", type=int, help="Number of training epochs")

    parser.add_argument(
        "--trainer",
        type=str,
        default="clf",
        choices=["clf"],  # add "lm" later
        help="Trainer type",
    )

    parser.add_argument(
        "--eval-interval",
        type=int,
        help="Evaluate every N training steps (if not set → evaluate every epoch)",
    )

    parser.add_argument(
        "--grad-clip",
        type=float,
        help="Clip gradients by global norm",
    )

    # ==========================================================
    # Optimizer
    # ==========================================================
    parser.add_argument(
        "--optimizer",
        type=str,
        choices=[
            "muon_mu2sgd_adamw",
            "muon_mars_mu2sgd_phase_decay",
            "muon_graddiff",
            "muon_graddiff_phase_decay",
            "muon_adamw",
            "muon_momentum_decay_adamw",
        ],
        help="Optimizer name",
    )

    parser.add_argument("--lr", type=float, help="Learning rate")
    parser.add_argument("--weight-decay", type=float, help="Weight decay")

    # Momentum-related parameters
    parser.add_argument("--momentum", type=float, help="Primary momentum")
    parser.add_argument("--second-momentum", type=float, help="Second momentum (beta2)")
    # MARS-style direction correction
    parser.add_argument("--mvr-gamma", type=float, help="Gamma parameter")

    # Non-2D / 1D parameter handling (e.g. MARS)
    parser.add_argument(
        "--non2d-betas",
        type=float,
        nargs=2,
        metavar=("BETA1", "BETA2"),
        help="Betas for non-2D parameters",
    )

    parser.add_argument(
        "--non2d-lr",
        type=float,
        help="Learning rate for non-2D parameters",
    )

    # ==========================================================
    # Scheduler
    # ==========================================================
    parser.add_argument(
        "--scheduler",
        type=str,
        choices=["cosine"],
        help="LR scheduler name",
    )

    # ==========================================================
    # WandB
    # ==========================================================
    parser.add_argument(
        "--wandb",
        action="store_true",
        help="Enable Weights & Biases logging",
    )

    parser.add_argument(
        "--wandb-project",
        type=str,
        help="WandB project name",
    )

    parser.add_argument(
        "--wandb-entity",
        type=str,
        help="WandB entity (username or team)",
    )

    parser.add_argument(
        "--wandb-run-name",
        type=str,
        help="Custom WandB run name",
    )

    parser.add_argument(

        "--clip-grad-norm",
        type=float,
        default=None,
        help="Max norm for gradient clipping (None disables clipping)."
    )
    parser.add_argument(
        "--no-save-csv",
        action="store_true",
        help="Skip saving per-run CSV (suite runner will write averaged CSV instead)",
    )

    return parser


def main():
    args = get_parser().parse_args()
    cfg = load_config(args)

    sharing_strategy = cfg.get("dataset", {}).get(
        "multiprocessing_sharing_strategy"
    )
    if sharing_strategy:
        torch.multiprocessing.set_sharing_strategy(str(sharing_strategy))
        print(f"DataLoader multiprocessing sharing strategy: {sharing_strategy}")

    set_seed(args.seed)

    requested = args.device
    if requested == "cuda" and not torch.cuda.is_available():
        print("WARNING: CUDA requested but not available, falling back to CPU")
        requested = "cpu"
    if requested == "mps" and not torch.backends.mps.is_available():
        print("WARNING: MPS requested but not available, falling back to CPU")
        requested = "cpu"
    device = torch.device(requested)

    # Free speed boost: cuDNN auto-tunes kernels for fixed input sizes.
    if device.type == "cuda":
        torch.backends.cudnn.benchmark = True
        torch.backends.cuda.matmul.allow_tf32 = True
        torch.backends.cudnn.allow_tf32 = True
        torch.set_float32_matmul_precision("high")

    train_dataset, test_dataset, train_eval_dataset = build_dataset(cfg)
    train_dataloader, test_dataloader, train_eval_dataloader = build_dataloader(
        train_dataset,
        test_dataset,
        cfg,
        train_eval_dataset,
    )

    model = build_model(cfg)
    model.to(device)

    optimizer = build_optimizer(model, cfg, args)

    scheduler = build_scheduler(
        optimizer,
        cfg,
        args,
    )

    trainer = build_trainer(
        model,
        optimizer,
        train_dataloader,
        test_dataloader,
        device,
        cfg,
        args,
        scheduler,
        train_eval_dataloader,
    )
    trainer.train(save_csv=not args.no_save_csv)


if __name__ == "__main__":
    main()

